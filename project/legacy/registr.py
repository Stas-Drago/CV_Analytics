def get_local_ip():
    try:
        # Создаём временный сокет и подключаемся к внешнему серверу (не отправляет данные)
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
            s.connect(("8.8.8.8", 80))  # Google DNS — просто для определения маршрута
            local_ip = s.getsockname()[0]  # Получаем IP, который используется по умолчанию
        return local_ip
    except Exception:
        return "Не удалось определить IP"

