def register_self_on_startup():
    time.sleep(3)  # Даём серверу время запуститься
    service_data = {
        'uuid': '8a1bb1b3-8377-4fe1-aae5-6e8448e6dda5',  # Уникальное имя
        'name': 'electronic_guardian_v1',
        'description': 'AI-система видеонаблюдения, которая анализирует поток с камер, отслеживает объекты, регистрирует события и отвечает на вопросы охранника в реальном времени.',
        'system_prompt': SISTEM_PROMT,
        'request_format': {},
        'endpoint': LOCAL_ENDPOINT
    }
    try:
        response = requests.post(EXTERNAL_SERVICE_URL, json=service_data, timeout=10)
        if response.status_code in [200, 201]:
            logger.info(f"✅ Сервис успешно зарегистрирован на {EXTERNAL_SERVICE_URL}")
            logger.info(f"📩 Ответ сервера: {response.json()}")
        else:
            logger.error(f"❌ Ошибка регистрации: HTTP {response.status_code}, {response.text}")
    except requests.exceptions.RequestException as e:
        logger.error(f"🚨 Не удалось подключиться к серверу регистрации: {e}")